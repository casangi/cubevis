'''The interfaces of the imaging layer (``devel/notes/drs/iclean/
iclean_imaging_layer_design.md``).

``ImagingSession`` is what the interactive clean GUI talks to: running
the imager (a ``Deconvolver``, today casatasks' ``gclean``) together with
access to the residual and mask images of each field (an ``ImageCube``
per field, reading and writing through an ``ImageStore``).  The local
implementation is ``LocalImagingSession``; a remote proxy (later) satisfies
the same protocol, as does an imager that is not CASA.

Nothing here imports CASA.
'''

from typing import Any, Dict, List, NamedTuple, Optional, Protocol, Tuple, runtime_checkable


class CycleResult(NamedTuple):
    '''What one step of the imager returns: the first (dirty) image from
    ``start()``, or one major cycle and its minor cycles from
    ``run_cycle()``.  A tuple, so code that unpacks gclean's six values
    unpacks this the same way.

    ``stopcode`` is gclean's ``StopCodes(major, minor)``; ``convergence``
    is a dict per field (gclean's nested dicts of lists, per channel and
    Stokes).'''
    stopdesc: str
    stopcode: Any
    majordone: int
    majorleft: int
    iterleft: int
    convergence: Dict[str, Any]


@runtime_checkable
class Deconvolver(Protocol):
    '''The surface of casatasks' ``gclean`` that the imaging layer uses.
    An RADPS/xradio imager can provide this and reuse ``LocalImagingSession``
    when its products can be read by an existing ``ImageStore``.'''

    def __next__(self) -> tuple: ...
    async def __anext__(self) -> tuple: ...
    def update(self, msg: dict) -> Tuple[int, str]: ...
    def image_products(self) -> List[dict]: ...
    def _log(self, history: bool = False) -> List[str]: ...
    def restore(self) -> dict: ...
    def has_next(self) -> bool: ...


@runtime_checkable
class ImageStore(Protocol):
    '''Primitive access to one image (the residual) and its mask, for one
    image format.  This is what a new image format implements (casatools
    today; xarray over arcae later).  Indices are lists: a plane is
    ``[stokes, chan]``; a spectrum is ``[x, y, stokes]``.'''

    image_path: Optional[str]
    mask_path: Optional[str]

    def shape(self) -> List[int]: ...
    def modified(self) -> float: ...
    def read_plane(self, index: List[int]) -> Any: ...
    def read_spectrum(self, index: List[int]) -> Any: ...
    def has_mask(self) -> bool: ...
    def open_mask(self, path: Optional[str]) -> None: ...
    def close_mask(self) -> None: ...
    def read_mask_plane(self, index: List[int]) -> Any: ...
    def write_mask_plane(self, index: List[int], pixels: Any) -> None: ...
    def read_mask_spectrum(self, index: List[int]) -> Any: ...
    def mask_pixel(self, chan: List[int], index: List[int]) -> int: ...
    def has_default_mask(self) -> bool: ...
    def read_default_mask(self) -> Any: ...
    def statistics(self, index: List[int], mask_path: Optional[str] = None) -> dict: ...
    def stokes_labels(self) -> List[str]: ...
    def fits_header(self) -> Tuple[Optional[dict], str]: ...
    def coordsys_record(self) -> dict: ...
    def close(self) -> None: ...


@runtime_checkable
class ImageCube(Protocol):
    '''One field's residual, mask and mask0 as the GUI uses them.  The
    implementation (``cubevis.imaging.ImageCube``) is written once, in
    numpy, over an ``ImageStore``; a remote proxy satisfies the same
    surface.  Display state (colormap bounds and transfer function) is
    the caller's and is passed in.'''

    image_path: Optional[str]
    mask_path: Optional[str]
    generation: int

    @property
    def shape(self) -> List[int]: ...
    def channel(self, index: List[int], pixel_type: Any, quant: Optional[dict] = None) -> Any: ...
    def channel_reply(self, index: List[int], quant: Optional[dict] = None, *,
                      stats: bool = False, hist_bins: Optional[int] = None) -> dict: ...
    def pixel_value(self, chan: List[int], index: List[int]) -> Any: ...
    def mask_value(self, chan: List[int], index: List[int]) -> int: ...
    def spectrum(self, index: List[int], mask: bool = False) -> Any: ...
    def statistics(self, index: List[int]) -> dict: ...
    def statistics_config(self, use_mask: Optional[bool] = None) -> None: ...
    def histogram(self, index: List[int], nbins: int) -> dict: ...
    def have_mask(self) -> bool: ...
    def have_mask0(self) -> bool: ...
    def mask0(self, index: List[int]) -> Any: ...
    def mask(self, index: List[int], modify: bool = False) -> Any: ...
    def put_mask(self, index: List[int], mask: Any) -> None: ...
    def set_mask_name(self, new_mask_path: Optional[str]) -> None: ...
    def stokes_labels(self) -> List[str]: ...
    def fits_header(self) -> Tuple[Optional[dict], str]: ...
    def coorddesc(self) -> dict: ...
    def touch(self) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class ImagingSession(Protocol):
    '''The imaging layer: the interactive clean GUI's only way to the
    imager and its images (and the boundary a remote proxy stands at).
    Results are plain data.'''

    def start(self) -> CycleResult: ...
    def update(self, params: dict) -> Tuple[int, str]: ...
    def run_cycle(self) -> CycleResult: ...
    async def arun_cycle(self) -> CycleResult: ...
    def has_next(self) -> bool: ...
    def log(self, history: bool = False) -> List[str]: ...
    def restore(self) -> dict: ...
    def stop_descriptions(self) -> Dict[int, str]: ...
    def fields(self) -> List[dict]: ...
    def cube(self, field: str) -> ImageCube: ...
    def close(self) -> None: ...
